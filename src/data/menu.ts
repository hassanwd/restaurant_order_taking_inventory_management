const slug = (name: string) => name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

const singleGroup = (
  id: string,
  name: string,
  choices: [string, number][],
): OptionGroup => ({
  id,
  name,
  type: "single",
  required: true,
  choices: choices.map(([label, price]) => ({ id: slug(label), name: label, price })),
});

const addOns = (choices: [string, number][]): OptionGroup => ({
  id: "addons",
  name: "Add-ons",
  type: "multi",
  required: false,
  choices: choices.map(([label, price]) => ({ id: slug(label), name: label, price })),
});

